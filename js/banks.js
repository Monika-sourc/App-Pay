function cleanDomain(domain) {
    if (!domain) return '';
    return domain
        .replace(/^https?:\/\//, '')
        .replace(/^www\./, '')
        .split('/')[0]
        .trim();
}

export function getBankLogoUrl(domain) {
    const d = cleanDomain(domain);
    if (!d) return '';
    if (CUSTOM_BANK_LOGOS[d]) return CUSTOM_BANK_LOGOS[d];
    return `https://logo.clearbit.com/${d}`;
}

export function getBankLogoUrls(domain) {
    const d = cleanDomain(domain);
    if (!d) return [];

    // Si on a un logo spécifique direct
    if (CUSTOM_BANK_LOGOS[d]) {
        return [
            CUSTOM_BANK_LOGOS[d],
            `https://logo.clearbit.com/${d}`, // Fallback 1
            `https://icon.horse/icon/${d}`    // Fallback 2
        ];
    }

    // Sinon, on utilise uniquement Clearbit et IconHorse.
    // On a SUPPRIMÉ Google Favicons et Unavatar qui créaient les lettres.
    return [
        `https://logo.clearbit.com/${d}`,
        `https://icon.horse/icon/${d}`,
        `https://icons.duckduckgo.com/ip3/${d}.ico`
    ];
}

export function getAllBanks() {
    const all = [];
    Object.entries(BANKS_BY_COUNTRY).forEach(([country, banks]) => {
        banks.forEach(bank => {
            all.push({ ...bank, country });
        });
    });
    return all;
}
